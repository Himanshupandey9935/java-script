// for Upper Case
let str = "himanshu"
console.log(str.toUpperCase()); 

// for lower Case
console.log(str.toLowerCase());

// for trimming the white space from starting to ending
let str2 = "  my name is himanshu pandey  "
console.log(str2.trim());

// for slicing the part of string 
console.log(str.slice(0,4));

//for adding the two strings
console.log(str.concat(str2));

// for replacing the value 
console.log(str.replace("h","m"))