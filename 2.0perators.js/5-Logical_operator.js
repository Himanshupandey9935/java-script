// logical operator examples

let a = 7;
let b = 6;
console.log(a>b && a==7); /* and operator (&&) = when both 
                         condition are true it give true */

console.log(a>b || a==8); /* OR operator (||) = when any one  
                         condition are true it give true */

console.log(!a>b); /* NOT operator (!) = it always give 
                  give opposite output */